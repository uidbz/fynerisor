package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/uidbz/fynerisor/gui/objattrs"
)

// fynerisor docs (issue #47): generate the API reference from the live
// registries (issue #38). Every wrapper type registers its attribute
// surface with objattrs, so the compiled binary is the single source of
// truth; docs/API.md and the API part of llms.txt are generated output.
// CI checks drift with `go generate` + `git diff --exit-code`.

func runDocs(argv []string) int {
	fs := flag.NewFlagSet("fynerisor docs", flag.ContinueOnError)
	_ = fs.Bool("markdown", true, "render Markdown (the default; the flag exists for script stability)")
	jsonOut := fs.Bool("json", false, "emit JSON instead of Markdown")
	out := fs.String("o", "", "write to file instead of stdout")
	fs.Usage = func() {
		fmt.Fprintf(os.Stderr, "Usage: fynerisor docs [--json] [-o file]\n\nGenerate the script API reference from the compiled attribute registries.\n")
		fs.PrintDefaults()
	}
	if err := fs.Parse(argv); err != nil {
		if err == flag.ErrHelp {
			return 0
		}
		return 2
	}

	specs := objattrs.All()

	var content string
	if *jsonOut {
		b, err := json.MarshalIndent(specs, "", "  ")
		if err != nil {
			fmt.Fprintln(os.Stderr, "fynerisor docs:", err)
			return 1
		}
		content = string(b) + "\n"
	} else {
		content = renderMarkdown(specs)
	}

	if *out != "" {
		if err := os.WriteFile(*out, []byte(content), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "fynerisor docs:", err)
			return 1
		}
		return 0
	}
	fmt.Print(content)
	return 0
}

func renderMarkdown(specs []objattrs.TypeSpecs) string {
	var b strings.Builder
	b.WriteString("# fynerisor API reference\n\n")
	b.WriteString("Generated by `fynerisor docs --markdown` from the compiled attribute\n")
	b.WriteString("registries (issue #38) — this file is the authoritative list of script-visible\n")
	b.WriteString("types and their attributes. Do not edit by hand; CI fails if it drifts from\n")
	b.WriteString("the code.\n\n")
	b.WriteString("Property entries are read by name (`t.Text`); callable entries are invoked\n")
	b.WriteString("with parentheses (`t.SetText(x)`).\n\n")

	for _, ts := range specs {
		if len(ts.Specs) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n", ts.TypeName)
		for _, a := range ts.Specs {
			args := a.DisplayArgs()
			isMethod := a.Returns != ""
			sig := a.Name
			if isMethod {
				sig = a.Name + "(" + strings.Join(args, ", ") + ")"
			}
			fmt.Fprintf(&b, "- `%s`", sig)
			if a.Returns != "" && a.Returns != "nil" {
				fmt.Fprintf(&b, " → %s", a.Returns)
			}
			if a.Doc != "" {
				fmt.Fprintf(&b, " — %s", a.Doc)
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	return b.String()
}
